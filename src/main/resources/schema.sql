CREATE TABLE IF NOT EXISTS GENRES
(
    GENRE_ID   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GENRE_NAME CHARACTER VARYING(50) not null
    CONSTRAINT GENRES_UNIQUE unique
);

CREATE TABLE IF NOT EXISTS RATINGS
(
    RATING_ID   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RATING_NAME CHARACTER VARYING(10) not null
    CONSTRAINT RATINGS_UNIQUE unique
);

CREATE TABLE IF NOT EXISTS FILMS
(
    FILM_ID      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILM_NAME    CHARACTER VARYING(100) not null,
    DESCRIPTION  CHARACTER VARYING(200),
    RELEASE_DATE DATE                   not null,
    DURATION     INTEGER                not null,
    RATING_ID    INTEGER,
    CONSTRAINT FILMS_RATINGS_FK FOREIGN KEY (RATING_ID) REFERENCES RATINGS(RATING_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS GENRES_RELATION
(
    FILM_ID            INTEGER not null,
    GENRE_ID           INTEGER not null,
    CONSTRAINT GENRES_RELATION_PK PRIMARY KEY (FILM_ID, GENRE_ID),
    CONSTRAINT GENRES_RELATION_FILMS_FK FOREIGN KEY (FILM_ID) REFERENCES FILMS(FILM_ID) ON DELETE CASCADE,
    CONSTRAINT GENRES_RELATION_GENRES_FK FOREIGN KEY (GENRE_ID) REFERENCES GENRES(GENRE_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS USERS
(
    USER_ID  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL    CHARACTER VARYING(50) not null
    CONSTRAINT USERS_UNIQUE_EMAIL unique,
    LOGIN    CHARACTER VARYING(50) not null
    CONSTRAINT USERS_UNIQUE_LOGIN unique,
    USERNAME CHARACTER VARYING(50) not null
    CONSTRAINT USERS_UNIQUE_USERNAME unique,
    BIRTHDAY DATE                  not null
);

CREATE TABLE IF NOT EXISTS FRIENDS_RELATION
(
    USER_ID             INTEGER not null,
    FRIEND_ID           INTEGER not null,
    CONSTRAINT FRIENDS_RELATION_PK PRIMARY KEY (USER_ID, FRIEND_ID),
    CONSTRAINT FRIENDS_RELATION_USERS_FRIEND_FK FOREIGN KEY (FRIEND_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FRIENDS_RELATION_USERS_USER_FK FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS LIKES_RELATION
(
    FILM_ID           INTEGER not null,
    USER_ID           INTEGER not null,
    CONSTRAINT LIKES_RELATION_PK PRIMARY KEY (FILM_ID, USER_ID),
    CONSTRAINT LIKES_RELATION_FILMS_FK FOREIGN KEY (FILM_ID) REFERENCES FILMS(FILM_ID) ON DELETE CASCADE,
    CONSTRAINT LIKES_RELATION_USERS_FK FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS REVIEWS (
    REVIEW_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENT VARCHAR(200) NOT NULL,
    IS_POSITIVE BOOLEAN NOT NULL,
    USER_ID INTEGER NOT NULL,
    FILM_ID INTEGER NOT NULL,
    USEFUL INTEGER NOT NULL,
    CONSTRAINT REVIEWS_USERS_FK FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT REVIEWS_FILMS_FK FOREIGN KEY (FILM_ID) REFERENCES FILMS(FILM_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS REVIEWS_REACTION (
    REVIEW_ID INTEGER NOT NULL,
    USER_ID INTEGER NOT NULL,
    TYPE_REACTION TINYINT NOT NULL,
    PRIMARY KEY (REVIEW_ID, USER_ID, TYPE_REACTION),
    CONSTRAINT REVIEWS_REACTION_REVIEWS_FK FOREIGN KEY (REVIEW_ID) REFERENCES REVIEWS(REVIEW_ID) ON DELETE CASCADE,
    CONSTRAINT REVIEWS_REACTION_USERS_FK FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);